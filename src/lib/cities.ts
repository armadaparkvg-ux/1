export function getCity(slug: string): CityPage | undefined {
  return CITIES.find((c) => c.slug === slug);
}

export function getCitySlugs(): string[] {
  return CITIES.map((c) => c.slug);
}

export function getCityNeighbors(slug: string): CityPage[] {
  const slugs = CITY_NEIGHBORS[slug] ?? [];
  return slugs
    .map((item) => getCity(item))
    .filter((city): city is CityPage => Boolean(city));
}
